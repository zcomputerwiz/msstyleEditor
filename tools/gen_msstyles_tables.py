import os
import re
import sys

def parse_definitions(filepath):
    """Parse IDENTIFIER enum from VisualStyleDefinitions.cs"""
    identifiers = {}
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    enum_match = re.search(r'public\s+enum\s+IDENTIFIER\s*\{([^}]+)\}', content)
    if enum_match:
        for line in enum_match.group(1).splitlines():
            line = line.strip()
            if '//' in line:
                line = line[:line.index('//')].strip()
            m = re.match(r'([A-Za-z0-9_]+)\s*=\s*([0-9]+)', line)
            if m:
                name, val = m.group(1), int(m.group(2))
                identifiers[name] = val
    return identifiers

def parse_property_map(filepath):
    """Parse PROPERTY_INFO_MAP from VisualStylePropertyMap.cs"""
    props = []
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    pattern = re.compile(r'\{\s*([0-9]+)\s*,\s*new\s+PropertyInfo\(\s*"([^"]+)"\s*,\s*([0-9]+)\s*,')
    for m in pattern.finditer(content):
        prop_id = int(m.group(1))
        name = m.group(2)
        type_id = int(m.group(3))
        props.append((prop_id, name, type_id))

    props.sort(key=lambda p: p[0])
    return props

def parse_enum_map(filepath, identifiers):
    """Parse enum lists and property-to-enum mappings from VisualStyleEnumMap.cs"""
    enums = {}
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    # Find enum lists
    list_pattern = re.compile(r'public\s+static\s+readonly\s+List<VisualStyleEnumEntry>\s+(ENUM_[A-Za-z0-9_]+)\s*=\s*new\s+List<VisualStyleEnumEntry>\(\)\s*\{([^}]+)\};', re.DOTALL)
    for m in list_pattern.finditer(content):
        enum_var = m.group(1)
        body = m.group(2)
        entries = []
        entry_pattern = re.compile(r'new\s+VisualStyleEnumEntry\(\s*([0-9]+)\s*,\s*"([^"]+)"\s*\)')
        for em in entry_pattern.finditer(body):
            val = int(em.group(1))
            ename = em.group(2)
            entries.append((val, ename))
        enums[enum_var] = entries

    # Find Find() mappings
    prop_to_enum = {}
    prop_pattern = re.compile(r'nameID\s*==\s*\(int\)IDENTIFIER\.([A-Za-z0-9_]+)\s*\)\s*\{?\s*return\s+VisualStyleEnums\.(ENUM_[A-Za-z0-9_]+);')
    for m in prop_pattern.finditer(content):
        id_name = m.group(1)
        enum_var = m.group(2)
        if id_name in identifiers:
            prop_to_enum[identifiers[id_name]] = enum_var

    # Range for HIGHCONTRASTTYPE
    range_match = re.search(r'nameID\s*>=\s*\(int\)IDENTIFIER\.([A-Za-z0-9_]+)\s*&&\s*nameID\s*<=\s*\(int\)IDENTIFIER\.([A-Za-z0-9_]+)\s*\)\s*\{?\s*return\s+VisualStyleEnums\.(ENUM_[A-Za-z0-9_]+);', content)
    if range_match:
        start_id = identifiers.get(range_match.group(1))
        end_id = identifiers.get(range_match.group(2))
        enum_var = range_match.group(3)
        if start_id and end_id:
            for pid in range(start_id, end_id + 1):
                prop_to_enum[pid] = enum_var

    return enums, prop_to_enum

def generate_header(identifiers, props, enums, prop_to_enum, output_path):
    """Generate C header file"""
    lines = []
    lines.append("/* Automatically generated by gen_msstyles_tables.py. Do not edit directly. */")
    lines.append("/*")
    lines.append(" * Portions derived from libmsstyle (https://github.com/nptr/msstyleEditor)")
    lines.append(" * Copyright (c) 2017-2022 nptr")
    lines.append(" * SPDX-License-Identifier: MIT")
    lines.append(" */")
    lines.append("")
    lines.append("#ifndef __MSSTYLES_V4_TABLES_H")
    lines.append("#define __MSSTYLES_V4_TABLES_H")
    lines.append("")
    lines.append("#include <stdlib.h>")
    lines.append("#include <string.h>")
    lines.append("")

    # Platforms
    lines.append("enum msstyles_platform {")
    lines.append("    MSSTYLES_PLATFORM_UNKNOWN = 0,")
    lines.append("    MSSTYLES_PLATFORM_VISTA   = 1,")
    lines.append("    MSSTYLES_PLATFORM_WIN7    = 2,")
    lines.append("    MSSTYLES_PLATFORM_WIN8    = 3,")
    lines.append("    MSSTYLES_PLATFORM_WIN81   = 4,")
    lines.append("    MSSTYLES_PLATFORM_WIN10   = 5,")
    lines.append("    MSSTYLES_PLATFORM_WIN11   = 6,")
    lines.append("};")
    lines.append("")

    # Property types
    type_ids = [
        ("MSSTYLE_TYPE_ENUM", 200, "ENUM"),
        ("MSSTYLE_TYPE_STRING", 201, "STRING"),
        ("MSSTYLE_TYPE_INT", 202, "INT"),
        ("MSSTYLE_TYPE_BOOL", 203, "BOOL"),
        ("MSSTYLE_TYPE_COLOR", 204, "COLOR"),
        ("MSSTYLE_TYPE_MARGINS", 205, "MARGINS"),
        ("MSSTYLE_TYPE_FILENAME", 206, "FILENAME"),
        ("MSSTYLE_TYPE_SIZE", 207, "SIZE"),
        ("MSSTYLE_TYPE_POSITION", 208, "POSITION"),
        ("MSSTYLE_TYPE_RECT", 209, "RECT"),
        ("MSSTYLE_TYPE_FONT", 210, "FONT"),
        ("MSSTYLE_TYPE_INTLIST", 211, "INTLIST"),
        ("MSSTYLE_TYPE_HBITMAP", 212, "HBITMAP"),
        ("MSSTYLE_TYPE_DISKSTREAM", 213, "DISKSTREAM"),
        ("MSSTYLE_TYPE_STREAM", 214, "STREAM"),
        ("MSSTYLE_TYPE_BITMAPREF", 215, "BITMAPREF"),
        ("MSSTYLE_TYPE_FLOAT", 216, "FLOAT"),
        ("MSSTYLE_TYPE_FLOATLIST", 217, "FLOATLIST"),
        ("MSSTYLE_TYPE_HIGHCONTRASTCOLORTYPE", 241, "HIGHCONTRASTCOLORTYPE"),
    ]

    lines.append("enum msstyles_type_id {")
    for c_name, val, _ in type_ids:
        lines.append(f"    {c_name} = {val},")
    lines.append("};")
    lines.append("")

    # Type name lookup
    lines.append("static inline const char *msstyles_get_type_name(int type_id)")
    lines.append("{")
    lines.append("    switch (type_id) {")
    for c_name, val, desc in type_ids:
        lines.append(f'    case {c_name}: return "{desc}";')
    lines.append('    default: return "UNKNOWN";')
    lines.append("    }")
    lines.append("}")
    lines.append("")

    # Property info struct
    lines.append("struct msstyles_prop_desc {")
    lines.append("    int id;")
    lines.append("    int type_id;")
    lines.append("    const char *name;")
    lines.append("};")
    lines.append("")

    lines.append(f"static const struct msstyles_prop_desc msstyles_props[{len(props)}] = {{")
    for pid, name, tid in props:
        lines.append(f'    {{ {pid}, {tid}, "{name}" }},')
    lines.append("};")
    lines.append("")

    # Binary search helper
    lines.append("static inline const struct msstyles_prop_desc *msstyles_find_prop_desc(int prop_id)")
    lines.append("{")
    lines.append(f"    int low = 0, high = {len(props)} - 1;")
    lines.append("    while (low <= high) {")
    lines.append("        int mid = low + (high - low) / 2;")
    lines.append("        if (msstyles_props[mid].id == prop_id)")
    lines.append("            return &msstyles_props[mid];")
    lines.append("        else if (msstyles_props[mid].id < prop_id)")
    lines.append("            low = mid + 1;")
    lines.append("        else")
    lines.append("            high = mid - 1;")
    lines.append("    }")
    lines.append("    return NULL;")
    lines.append("}")
    lines.append("")

    # Enum structures
    lines.append("struct msstyles_enum_val {")
    lines.append("    int value;")
    lines.append("    const char *name;")
    lines.append("};")
    lines.append("")

    for var_name, entries in sorted(enums.items()):
        c_var = var_name.lower()
        lines.append(f"static const struct msstyles_enum_val msstyles_{c_var}[{len(entries)}] = {{")
        for val, ename in entries:
            lines.append(f'    {{ {val}, "{ename}" }},')
        lines.append("};")
        lines.append("")

    lines.append("struct msstyles_enum_map_entry {")
    lines.append("    int prop_id;")
    lines.append("    const struct msstyles_enum_val *values;")
    lines.append("    int count;")
    lines.append("};")
    lines.append("")

    sorted_p2e = sorted(prop_to_enum.items(), key=lambda x: x[0])
    lines.append(f"static const struct msstyles_enum_map_entry msstyles_prop_enums[{len(sorted_p2e)}] = {{")
    for pid, enum_var in sorted_p2e:
        count = len(enums[enum_var])
        c_var = enum_var.lower()
        lines.append(f"    {{ {pid}, msstyles_{c_var}, {count} }},")
    lines.append("};")
    lines.append("")

    lines.append("static inline const char *msstyles_find_enum_name(int prop_id, int val)")
    lines.append("{")
    lines.append(f"    int low = 0, high = {len(sorted_p2e)} - 1;")
    lines.append("    while (low <= high) {")
    lines.append("        int mid = low + (high - low) / 2;")
    lines.append("        if (msstyles_prop_enums[mid].prop_id == prop_id) {")
    lines.append("            int i;")
    lines.append("            for (i = 0; i < msstyles_prop_enums[mid].count; i++) {")
    lines.append("                if (msstyles_prop_enums[mid].values[i].value == val)")
    lines.append("                    return msstyles_prop_enums[mid].values[i].name;")
    lines.append("            }")
    lines.append('            return "UNKNOWN_VALUE";')
    lines.append("        }")
    lines.append("        else if (msstyles_prop_enums[mid].prop_id < prop_id)")
    lines.append("            low = mid + 1;")
    lines.append("        else")
    lines.append("            high = mid - 1;")
    lines.append("    }")
    lines.append("    return NULL;")
    lines.append("}")
    lines.append("")

    # Platform detection helper from class name list
    lines.append("static inline enum msstyles_platform msstyles_detect_platform_from_classes(int (*has_class)(const void *ctx, const char *name), const void *ctx)")
    lines.append("{")
    lines.append('    if (has_class(ctx, "DarkMode::TaskManager")) return MSSTYLES_PLATFORM_WIN11;')
    lines.append('    if (has_class(ctx, "W8::TaskbandExtendedUI")) return MSSTYLES_PLATFORM_WIN81;')
    lines.append('    if (has_class(ctx, "DWMTouch") || has_class(ctx, "DWMPen")) return MSSTYLES_PLATFORM_WIN10;')
    lines.append('    if (has_class(ctx, "QueryBuilder")) return MSSTYLES_PLATFORM_VISTA;')
    lines.append("    return MSSTYLES_PLATFORM_WIN7;")
    lines.append("}")
    lines.append("")

    lines.append("#endif /* __MSSTYLES_V4_TABLES_H */")
    lines.append("")

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print(f"Generated {output_path} with {len(props)} properties and {len(enums)} enums.")

def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    repo_dir = os.path.dirname(script_dir)
    lib_dir = os.path.join(repo_dir, "libmsstyle")

    def_path = os.path.join(lib_dir, "VisualStyleDefinitions.cs")
    prop_path = os.path.join(lib_dir, "VisualStylePropertyMap.cs")
    enum_path = os.path.join(lib_dir, "VisualStyleEnumMap.cs")

    out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(script_dir, "msstyles_v4_tables.h")

    identifiers = parse_definitions(def_path)
    props = parse_property_map(prop_path)
    enums, p2e = parse_enum_map(enum_path, identifiers)

    generate_header(identifiers, props, enums, p2e, out_path)

if __name__ == '__main__':
    main()
